import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
const ids={admin:'10000000-0000-4000-8000-000000000001',staff:'10000000-0000-4000-8000-000000000002',other:'10000000-0000-4000-8000-000000000003',stranger:'10000000-0000-4000-8000-000000000004',session:'20000000-0000-4000-8000-000000000001',receipt:'30000000-0000-4000-8000-000000000001',receipt2:'30000000-0000-4000-8000-000000000002',undo:'40000000-0000-4000-8000-000000000001'};
test('database enforces staff access, roles, receiving counts and permanent corrections',async()=>{
 const db=new PGlite();
 try{
  await db.exec(`create role anon; create role authenticated; create schema auth;
   create table auth.users(id uuid primary key,email text,invited_at timestamptz);
   create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
   grant usage on schema public,auth to anon,authenticated;`);
  await db.exec(await readFile(new URL('../supabase/migrations/202611090001_scanner.sql',import.meta.url),'utf8'));
  await db.query(`insert into auth.users values($1,'ryan@sepsmanagement.com',now()),($2,'staff@example.com',now()),($3,'other@example.com',now()),($4,'stranger@example.com',null)`,[ids.admin,ids.staff,ids.other,ids.stranger]);
  await db.exec(await readFile(new URL('../supabase/bootstrap-admin.sql',import.meta.url),'utf8'));
  async function asUser(id,fn,role='authenticated'){return db.transaction(async tx=>{await tx.exec('set local role '+role);await tx.query(`select set_config('request.jwt.claim.sub',$1,true)`,[id||'']);return fn(tx);});}
  const query=(id,sql,args=[])=>asUser(id,tx=>tx.query(sql,args));
  assert.equal((await db.query('select count(*)::integer n from public.seps_staff')).rows[0].n,3,'only invitations enroll');
  const rows=[{id:'14888346',bl:'TSCW 19117078',name:'JAYS EUX',container:'SEGU3921667',expected:1}];
  const createArgs=[ids.session,'SEGU3921667','TE1804','manifest.pdf',true,JSON.stringify(rows)];
  const createSql='select public.seps_create_session($1,$2,$3,$4,$5,$6::jsonb)';
  await assert.rejects(query(ids.stranger,createSql,createArgs),/Active staff/);
  await assert.rejects(asUser(null,tx=>tx.query(createSql,createArgs),'anon'),/permission denied/);
  await query(ids.staff,createSql,createArgs);
  await query(ids.staff,createSql,createArgs);
  assert.equal((await db.query('select count(*)::integer n from public.seps_sessions')).rows[0].n,1,'same import request is idempotent');
  await assert.rejects(query(ids.other,createSql,createArgs),/request ID already used/);
  const badArgs=[...createArgs];badArgs[0]='20000000-0000-4000-8000-000000000099';badArgs[5]=JSON.stringify([{...rows[0],expected:1.5}]);
  await assert.rejects(query(ids.staff,createSql,badArgs),/Invalid shipment/);
  assert.equal((await db.query('select count(*)::integer n from public.seps_sessions')).rows[0].n,1,'failed import rolls back');
  assert.equal((await query(ids.stranger,'select * from public.seps_sessions')).rows.length,0,'uninvited account sees no sessions');
  await assert.rejects(query(ids.staff,"update public.seps_shipments set received=99"),/permission denied/);
  await assert.rejects(query(ids.staff,"update public.seps_staff set role='admin'"),/permission denied/);
  await assert.rejects(query(ids.staff,'select public.seps_set_staff($1,$2,$3)',[ids.staff,'admin',true]),/Administrator/);
  const receiveSql='select public.seps_receive($1,$2,$3)';
  await query(ids.staff,receiveSql,[ids.receipt,ids.session,'14888346']);
  await query(ids.staff,receiveSql,[ids.receipt,ids.session,'14888346']);
  assert.equal((await db.query('select received from public.seps_shipments')).rows[0].received,1,'retry counts once');
  await assert.rejects(query(ids.staff,receiveSql,[ids.receipt2,ids.session,'14888346']),/already complete/);
  await assert.rejects(query(ids.staff,receiveSql,[ids.receipt2,ids.session,'unknown']),/Unknown barcode/);
  await assert.rejects(query(ids.other,receiveSql,[ids.receipt,ids.session,'14888346']),/request ID already used/);
  const undoSql='select public.seps_undo($1,$2,$3)';
  await assert.rejects(query(ids.other,undoSql,[ids.undo,ids.receipt,'wrong person']),/own receipts/);
  await query(ids.staff,undoSql,[ids.undo,ids.receipt,'Scanned wrong box']);
  await query(ids.staff,undoSql,[ids.undo,ids.receipt,'Scanned wrong box']);
  assert.equal((await db.query('select received from public.seps_shipments')).rows[0].received,0);
  assert.equal((await db.query('select count(*)::integer n from public.seps_scan_events')).rows[0].n,2,'original receipt remains');
  await assert.rejects(query(ids.staff,undoSql,['40000000-0000-4000-8000-000000000099',ids.receipt,'twice']),/already corrected/);
  await assert.rejects(query(ids.staff,'delete from public.seps_scan_events'),/permission denied/);
  await assert.rejects(query(ids.admin,'select public.seps_set_staff($1,$2,$3)',[ids.admin,'staff',true]),/one active administrator/);
  await query(ids.admin,'select public.seps_set_staff($1,$2,$3)',[ids.staff,'staff',false]);
  assert.equal((await query(ids.staff,'select * from public.seps_sessions')).rows.length,0,'disabled users cannot read');
  await assert.rejects(query(ids.staff,receiveSql,[ids.receipt2,ids.session,'14888346']),/Active staff/);
  await query(ids.admin,'select public.seps_set_staff($1,$2,$3)',[ids.staff,'staff',true]);
  await query(ids.staff,receiveSql,[ids.receipt2,ids.session,'14888346']);
  await query(ids.admin,undoSql,['40000000-0000-4000-8000-000000000002',ids.receipt2,'Administrator correction']);
  assert.equal((await db.query('select sum(delta)::integer net from public.seps_scan_events')).rows[0].net,0);
 }finally{await db.close();}
});
